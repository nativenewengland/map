def solve(A):
 for i in range(3):
  k=max(range(i,3),key=lambda j:abs(A[j][i]));A[i],A[k]=A[k],A[i]
  s=A[i][i];A[i]=[v/s for v in A[i]]
  for j in range(3):
   if j!=i:
    v=A[j][i];A[j]=[a-v*b for a,b in zip(A[j],A[i])]
 return A[0][3]
